#!/usr/bin/env python3
"""
Convert curated John Tromp / James D. Allen Connect-Four joseki and match lines
into the same move-row format used by the Connect4 project.

Source page:
    https://tromp.github.io/c4.html

What this script writes
-----------------------
Rows in the same broad schema as c4_move_data_generator.py:

    label, reward, game, ply, action, p0..p6, player, 0-0..5-6

Board convention:
    - numpy shape (6, 7)
    - board[0, :] is the top row
    - board[5, :] is the bottom row
    - values are {0, 1, 2}
        0 = empty
        1 = first player / X / Eques / uppercase source moves
        2 = second player / O / Knott / lowercase source moves

Two output families are supported:

1) Expert rows, from the curated Tromp/Allen move sequences.
   For every unique prefix, the next expert move(s) become p0..p6.
   If multiple curated lines share a position with different expert continuations,
   the policy is uniform over those shown continuations.

2) Optional LA rows, generated from the same joseki prefixes.
   For every unique prefix position, your Connect4Lookahead labels the position
   with action and p0..p6 uniform among tied-best moves.

Spyder usage
------------
Place this file somewhere inside your project tree. If it lives inside C4/, the
script automatically adds the parent project directory to sys.path and imports:

    from C4.fast_connect4_lookahead import Connect4Lookahead

Then just press Run.

Important
---------
The curated move list below is intentionally small and readable. It contains
clear linear move lines from the Tromp page. Add more lines to CURATED_LINES
using the same syntax if you want to expand the pack.
"""

